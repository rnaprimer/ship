const CELL_W = 6;
const CELL_H = 9;
const PER_ROW = 16;
export const FONT_LINE_HEIGHT = 9;

export function buildFont(imageFile: string): { canvas: Canvas; xml: string } {
  const chars = Object.keys(GLYPHS);
  const rows = Math.ceil((chars.length + 1) / PER_ROW);
  const canvas = new Canvas(PER_ROW * CELL_W, rows * CELL_H);
  const entries: string[] = [];

  chars.forEach((ch, i) => {
    const rowsOfGlyph = GLYPHS[ch].split("|");
    const width = Math.max(...rowsOfGlyph.map((r) => r.length));
    const cx = (i % PER_ROW) * CELL_W;
    const cy = Math.floor(i / PER_ROW) * CELL_H;
    rowsOfGlyph.forEach((r, y) =>
      [...r].forEach((p, x) => {
        if (p === "#") canvas.set(cx + x, cy + y, "#ffffff");
      }),
    );
    entries.push(
      `    <char id="${ch.codePointAt(0)}" x="${cx}" y="${cy}" width="${width}" height="8" xoffset="0" yoffset="0" xadvance="${width + 1}" page="0" chnl="15" />`,
    );
  });
  // Space: no pixels, just advance.
  entries.push(`    <char id="32" x="0" y="0" width="0" height="0" xoffset="0" yoffset="0" xadvance="3" page="0" chnl="15" />`);

  const xml = [
    `<?xml version="1.0"?>`,
    `<font>`,
    `  <info face="ShipPixel" size="8" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="1,1" />`,
    `  <common lineHeight="${FONT_LINE_HEIGHT}" base="7" scaleW="${canvas.width}" scaleH="${canvas.height}" pages="1" packed="0" />`,
    `  <pages>`,
    `    <page id="0" file="${imageFile}" />`,
    `  </pages>`,
    `  <chars count="${entries.length}">`,
    ...entries,
    `  </chars>`,
    `</font>`,
    ``,
  ].join("\n");

  return { canvas, xml };
}
